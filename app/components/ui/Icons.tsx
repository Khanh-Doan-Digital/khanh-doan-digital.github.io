export type Platform = keyof typeof platformLogos;

export const platforms = Object.keys(platformLogos) as Platform[];

// Some logo curves touch or overshoot their viewBox edge, which clips when zoomed in.
const logoPadding = 6;

export function PlatformIcon({ name }: { name: Platform }) {
  const { viewBox, paths } = platformLogos[name];
  const [, , width, height] = viewBox.split(" ").map(Number);
  const paddedWidth = width + logoPadding * 2;
  const paddedHeight = height + logoPadding * 2;

  return (
    <svg
      className="platform-icon"
      viewBox={`${-logoPadding} ${-logoPadding} ${paddedWidth} ${paddedHeight}`}
      style={{ aspectRatio: `${paddedWidth} / ${paddedHeight}` }}
      role="img"
      aria-label={name}
      focusable="false"
    >
      <title>{name}</title>
      {paths.map((path) => <path key={path.d} fill={path.fill} d={path.d} />)}
    </svg>
  );
}

