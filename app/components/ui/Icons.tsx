export function isPlatform(name: string): name is Platform {
  return Object.hasOwn(platformLogos, name);
}

// Some logo curves touch or overshoot their viewBox edge, which clips when zoomed in.
const logoPaddingRatio = 6 / 256;

export function PlatformIcon({ name, onLight = false }: { name: Platform; onLight?: boolean }) {
  const { viewBox, paths }: PlatformLogo = platformLogos[name];
  const [minX, minY, width, height] = viewBox.split(" ").map(Number);
  const logoPadding = width * logoPaddingRatio;
  const paddedWidth = width + logoPadding * 2;
  const paddedHeight = height + logoPadding * 2;

  return (
    <svg
      className="platform-icon"
      viewBox={`${minX - logoPadding} ${minY - logoPadding} ${paddedWidth} ${paddedHeight}`}
      style={{ aspectRatio: `${paddedWidth} / ${paddedHeight}` }}
      role="img"
      aria-label={name}
      focusable="false"
    >
      <title>{name}</title>
      {paths.map((path) => <path key={path.d} fill={onLight ? path.onLight ?? path.fill : path.fill} d={path.d} />)}
    </svg>
  );
}

